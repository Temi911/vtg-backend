#!/usr/bin/env node
// Builds supabase/functions/vtg-ai-assistant/site-knowledge.ts from the public VTG pages so the AI can describe the real site.
// Usage: node scripts/build-ai-site-knowledge.mjs
import fs from 'node:fs';
const PAGES = [
  ['frontend-v3.html', 'Home'], ['about-vintage.html', 'About VTG'], ['marketplace.html', 'Marketplace'], ['sourcing-suppliers.html', 'Sourcing and suppliers'],
  ['logistics-shipping.html', 'Logistics and shipping'], ['finance-payments.html', 'Finance and payments'], ['market-intelligence.html', 'Market intelligence'],
  ['intelligence-centre.html', 'Intelligence centre'], ['africa-markets.html', 'Africa markets'], ['trade-atlas.html', 'Trade Atlas'], ['partnerships.html', 'Partnerships'],
  ['inspection-request.html', 'Inspections'], ['product-verification.html', 'Product verification'], ['account-help.html', 'Account help'], ['contact.html', 'Contact'],
  ['signup.html', 'Sign up'], ['signin.html', 'Sign in'],
];
const text = (h) => h.replace(/<(script|style|svg|noscript)[\s\S]*?<\/\1>/gi, ' ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&rsquo;|&#39;/g, "'").replace(/&middot;/g, '·').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
const out = [];
for (const [file, label] of PAGES) {
  if (!fs.existsSync(file)) continue;
  const html = fs.readFileSync(file, 'utf8');
  const desc = (html.match(/<meta name="description" content="([^"]*)"/i) || [])[1] || '';
  const heads = [...html.matchAll(/<h[1-3][^>]*>([\s\S]*?)<\/h[1-3]>/gi)].map((m) => text(m[1])).filter((t) => t.length > 3 && t.length < 120);
  const paras = [...html.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/gi)].map((m) => text(m[1])).filter((t) => t.length > 50 && t.length < 400);
  const uniq = (a) => [...new Set(a)].filter((t) => !/['"]\s*\+|\+\s*['"]|\$\{|\{\{|esc\(/.test(t));
  const line = `${label} (/${file}): ${desc} Topics: ${uniq(heads).slice(0, 8).join('; ')}. ${uniq(paras).slice(0, 3).join(' ')}`.replace(/\s+/g, ' ').slice(0, 900);
  out.push(line);
}
const body = out.join('\n').replace(/`/g, "'").replace(/\$\{/g, '$ {');
fs.writeFileSync('supabase/functions/vtg-ai-assistant/site-knowledge.ts',
  '// GENERATED by scripts/build-ai-site-knowledge.mjs from the public VTG pages. Do not edit by hand.\nexport const SITE_KNOWLEDGE = `' + body + '`;\n');
fs.writeFileSync('api/ai/_site-knowledge.js',
  '// GENERATED by scripts/build-ai-site-knowledge.mjs from the public VTG pages. Do not edit by hand.\nmodule.exports = { SITE_KNOWLEDGE: ' + JSON.stringify(body) + ' };\n');
console.log('pages', out.length, 'chars', body.length);
